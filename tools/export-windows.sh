#!/usr/bin/env bash
# 윈도우 x86_64 실행 파일을 내보내 dist/WTW-<단계>-windows.zip 으로 묶는다.
# .NET 실행에 필요한 파일이 모두 들어가므로 사용자 PC 에 따로 설치할 것이 없다.
# 사용: tools/export-windows.sh [단계 이름, 기본 = game/project.godot 의 config/version]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/tools/env.sh"
STAGE="${1:-$(sed -n 's/^config\/version="\(.*\)"/\1/p' "$ROOT/game/project.godot")}"
[ -n "$STAGE" ] || { echo "[export] 단계 이름을 찾지 못했다 (game/project.godot 의 config/version)"; exit 1; }
OUTDIR="$ROOT/build/WTW"
ZIP="$ROOT/dist/WTW-${STAGE}-windows.zip"
cd "$ROOT"
rm -rf "$OUTDIR"; mkdir -p "$OUTDIR" "$ROOT/dist"
"$GODOT" --headless --path game --import >/dev/null 2>&1 || true
"$GODOT" --headless --path game --export-release "Windows" "$OUTDIR/WTW.exe" 2>&1 | grep -Ei "error|fail|warn" | grep -v "^\s*at " || true
if [ ! -f "$OUTDIR/WTW.exe" ]; then echo "[export] 실패: WTW.exe 가 없다"; exit 1; fi
cp game/fonts/OFL.txt "$OUTDIR/FONT-LICENSE-NanumGothic-OFL.txt"
cat > "$OUTDIR/읽어보기.txt" <<TXT
WTW (Watch The World) — ${STAGE}

1. 이 폴더를 통째로 둔 채 WTW.exe 를 두 번 누르면 실행됩니다.
2. 윈도우가 "Windows의 PC 보호" 경고를 띄우면 "추가 정보" → "실행" 을 누르세요.
   (서명하지 않은 실행 파일이라 처음 한 번 나오는 경고입니다.)
3. 켜면 "새 세계" 화면이 나옵니다. [만들기] 를 누르면 행성이 만들어집니다.
4. 지구본: 왼쪽 끌기 = 돌리기, 휠 = 가까이·멀리, 칸 누르기 = 칸 정보, 화살표 키 = 돌리기.
   지도 모드: Q 자연 · W 높낮이 · E 생물군계 · R 기온 · T 강수 · Y 자원 · U 언어 · I 지식 (아래 막대 단추로도).
   스페이스 = 멈춤, 1~5 = 1배속~5배속, F5 = 저장(멈춘 다음), F9 = 불러오기, Esc = 창 닫기.
5. 지방(2D): 땅 칸을 두 번 누르거나 칸 정보의 [들어가기] (또는 Enter).
   끌기 = 이동, 휠 = 가까이·멀리, 화살표 키 = 이동, 마우스를 올리면 작은 카드, 누르면 정보 창.
   위쪽 [이 지방만] / [이웃까지] · [자원 보기] (Y — 바위 · 광맥 · 돌만 밝게) · [지구본으로] (Esc).
   왼쪽 "지방 정보" 칸: 그 지방의 시각 · 기온 · 바람 · 바위 · 물 · 자원 … 줄마다 [자세히 보기] 로 이유. 제목을 누르면 접힘.
   지도의 밝기는 그 지방의 시각을 따라 낮 · 저녁 · 밤으로 바뀝니다(맨 위 시계는 세계 시간).
   갈색 = 걸을 수 있는 땅, 밝은 회색 = 드러난 바위(못 지나감), 빗금 어두운 회색 = 숨은 바위 속, 검정 = 아직 아무도 안 들어가 본 동굴.
   지구본의 붉은 점 = 화산(들어가면 가운데에 분화구, 둘레에 흑요석).
6. 사람(E3): 지방 화면 아래 [사람 뿌리기] / [가족 뿌리기] 를 누르고 땅을 누르면 그 자리에 사람이 생깁니다(오른쪽 단추 · Esc = 그만).
   사람에 마우스를 올리면 작은 카드, 누르면 큰 카드(개요 · 능력 · 몸 · 마음 · 관계 · 지식 · 이야기). [따라가기] 로 카메라가 따라갑니다.
   오른쪽 위 "사람 목록"에서 이름을 누르면 그 사람으로. 오른쪽 아래 알림(태어남 · 죽음 · 짝 · 무너짐)을 누르면 그 사람으로.
   지구본에서 사람이 사는 칸에는 사람 모양 + 인원이 보이고, 아직 아무도 산 적 없는 땅은 살짝 흐릿합니다.
7. 지방 넘기(E3b): 사람은 물 · 먹을 것이 없거나 모자라면, 또는 짝을 찾거나 궁금해서 지방 경계를 걸어서 넘어갑니다.
   [따라가기] 하던 사람이 경계를 넘으면 카메라도 그 지방으로 넘어갑니다. [이 지방만] 일 때 경계를 넘어가면 가장자리에 "○○가 국경을 넘어감" 표시가 잠깐 남습니다.
   지구본의 작은 노란 화살표 = 최근 3년 동안 사람이 옮겨 간 방향. 사람들이 땅에 이름을 붙이면 칸 정보 · 지방 제목에 "이름(뜻)"이 나옵니다.
   언어 지도(U): 사람 사는 칸을 그 칸의 말 색으로(뒤에 땅 모양이 흐릿하게). 칸을 누르면 그 말이 어디까지 통하는지(밝을수록 잘 통함).
8. 재료와 발견(E4): 사람은 "따뜻했으면 · 날카로운 게 있었으면 · 물을 담을 게 있었으면 …" 하는 바람이 생기면 손에 든 재료로 이것저것 해 봅니다.
   정해진 조리법이 아니라 재료의 성질(단단함 · 잘 탐 · 빚어짐 …)과 불의 세기로 결과가 정해집니다. 반쯤 된 것은 "실마리"로 기억합니다.
   모닥불 · 화덕 · 숯 · 돌칼 · 도끼 · 끈 · 바구니 · 토기 · 구리 … 처음 만든 사람과 해는 [지식의 행방] 창(D)에 남습니다.
   아는 사람이 모두 죽으면 그 발견은 사라집니다(알림 ✕). 옆에서 보던 사람은 따라 배웁니다.
   큰 카드의 [지식] 칸: 바람 · 아는 것 · 실마리 · 새로 만든 낱말(빌려 온 말은 어디서 왔는지). 밤에는 불빛이 둘레를 밝힙니다.
9. 넘기기(N): 아래 [넘기기] — 10년 · 50년 · 다음 발견 · 고른 물건을 알아낼 때까지 · 퍼질 때까지 · 새 땅 · 땅 이름 · 말 갈라짐 · 인구.
   넘기는 동안은 지도를 그리지 않고 가장 빠르게 돌립니다([그만]으로 멈춤). 끝나면 "그동안 일어난 일".
   큰 일(★★★ 세계에서 처음 발견 · 발견이 사라짐 · 말이 갈라짐)이 생기면 멈추고 알려 줍니다 — [그곳으로 가기] [계속] [이런 일로는 멈추지 않기].
   ★★ 무리의 일은 오른쪽 아래 알림만, ★ 한 사람의 일(태어남 · 죽음 · 무너짐)은 그 지방을 보고 있을 때만 알립니다.
10. 시험용 장면: [불러오기]에서 "첫 불 직전" · "50년 뒤 마을" · "마지막 장인이 늙음"을 고르면 바로 그 장면에서 시작합니다.
11. 지식(E5): 아는 법은 사람 머릿속에만 있습니다. 아는 사람이 아이 · 가족 · 물어 온 사람에게 가르치고(조금씩 쌓임, 말이 다르면 느림),
   곁에서 보고 따라 하기도 합니다(더 느림). 2년 넘게 안 쓰면 흐려지고, 아주 흐려지면 잊습니다. 늙으면 조금씩 잊습니다.
   나이 든 장인 · 무리에서 혼자 아는 사람은 동굴 벽 · 바위 면 · 나무껍질에 그림으로 남깁니다(숯 · 재 · 진흙). 그림은 말을 몰라도 조금은 알아봅니다.
   지방 화면의 그림을 누르면 무엇을 그린 것 같은지 · 누가 · 언제. 머리 위 표시: 손짓 = 가르치는 중, 물음표 = 배우는 중, 눈 = 그림을 보는 중.
   [지식의 행방] 창(D): 발견마다 [자세히] — 지금 누가 아나(무리 · 아는 정도) · 어디에 남았나(그림) · 잃음과 되찾음의 역사 · 낱말.
   지구본 [지식] 지도(I): 고른 발견을 아는 사람이 사는 칸이 밝은 금빛, 그림만 남은 칸은 보랏빛.
   [넘기기] → 지식: "세계에서 사라짐" · "무리에서 끊김" · "되찾음" 까지.
TXT
rm -f "$ZIP"
(cd "$OUTDIR/.." && zip -qr "$ZIP" "$(basename "$OUTDIR")")
echo "[export] $ZIP ($(du -h "$ZIP" | cut -f1))"
